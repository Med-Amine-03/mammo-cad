// ── Client-side only (uses localStorage) ─────────────────────────────────
export function getLang(): Lang {
  if (typeof window === 'undefined') return DEFAULT_LANG
  return (localStorage.getItem(LS_LANG) as Lang) || DEFAULT_LANG
}

export function setLang(l: Lang) {
  if (typeof window === 'undefined') return
  localStorage.setItem(LS_LANG, l)
  document.documentElement.setAttribute('lang', l)
  langListeners.forEach(fn => { try { fn(l) } catch {} })
}

export function toggleLang() {
  setLang(getLang() === 'fr' ? 'en' : 'fr')
}

const langListeners = new Set<(l: Lang) => void>()

export function subscribeLang(fn: (l: Lang) => void): () => void {
  langListeners.add(fn)
  return () => { langListeners.delete(fn) }
}

export function t(key: string): string {
  const l = getLang()
  const v = dict[l]?.[key]
  if (v !== undefined) return v
  return dict[DEFAULT_LANG]?.[key] ?? key
}

export function tBadge(raw?: string | null): string {
  if (!raw) return t('badge.UNKNOWN')
  return t('badge.' + String(raw).toUpperCase()) || raw
}
